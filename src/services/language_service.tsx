// React Context
interface LanguageContextType {
  currentLanguage: LanguageOption;
  setLanguage: (code: string) => void;
  languages: LanguageOption[];
  isEnglish: boolean;
  t: (key: string, fallback?: string) => string;
  tDual: (key: string, fallback?: string) => { primary: string; secondary?: string };
  tFood: (foodName: string) => { primary: string; secondary?: string };
  tIngredient: (ingredientName: string) => { primary: string; secondary?: string };
  tCategory: (category: string) => string;
}

export const LanguageContext = createContext<LanguageContextType>({
  currentLanguage: ALL_INDIAN_LANGUAGES[0],
  setLanguage: () => {},
  languages: ALL_INDIAN_LANGUAGES,
  isEnglish: true,
  t: (k, f) => f || k,
  tDual: (k, f) => ({ primary: f || k }),
  tFood: (n) => ({ primary: n }),
  tIngredient: (n) => ({ primary: n }),
  tCategory: (c) => c
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLanguage, setCurrentLanguageState] = useState<LanguageOption>(() =>
    LanguageService.getCurrentLanguage()
  );

  useEffect(() => {
    const unsub = LanguageService.subscribe((newLang) => {
      setCurrentLanguageState(newLang);
    });
    return () => unsub();
  }, []);

  const handleSetLanguage = (code: string) => {
    LanguageService.setLanguage(code);
  };

  const isEnglish = currentLanguage.code === 'en';

  const t = (key: string, fallback?: string) => LanguageService.t(key, fallback);
  const tDual = (key: string, fallback?: string) => LanguageService.tDual(key, fallback);
  const tFood = (name: string) => LanguageService.tFood(name);
  const tIngredient = (name: string) => LanguageService.tIngredient(name);
  const tCategory = (cat: string) => LanguageService.tCategory(cat);

  return (
    <LanguageContext.Provider
      value={{
        currentLanguage,
        setLanguage: handleSetLanguage,
        languages: ALL_INDIAN_LANGUAGES,
        isEnglish,
        t,
        tDual,
        tFood,
        tIngredient,
        tCategory
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

/**
 * Universal Dual-Text Component
 */
export const DualText: React.FC<{
  textKey?: string;
  fallback: string;
  className?: string;
  miniClassName?: string;
  inline?: boolean;
}> = ({
  textKey,
  fallback,
  className = 'font-bold text-slate-900',
  miniClassName = 'text-[10px] sm:text-[11px] text-slate-500 font-medium leading-tight',
  inline = false
}) => {
  const { isEnglish, t } = useLanguage();

  if (isEnglish) {
    return <span className={className}>{fallback}</span>;
  }

  const primaryText = textKey ? t(textKey, fallback) : fallback;

  if (inline) {
    return (
      <span className="inline-flex items-baseline gap-1.5 flex-wrap">
        <span className={className}>{primaryText}</span>
        {primaryText !== fallback && (
          <span className={miniClassName}>({fallback})</span>
        )}
      </span>
    );
  }

  return (
    <div className="flex flex-col text-left">
      <span className={className}>{primaryText}</span>
      {primaryText !== fallback && (
        <span className={miniClassName}>{fallback}</span>
      )}
    </div>
  );
};

/**
 * Dual Food Name Component
 * Formats:
 * Primary: Selected Indian language name (e.g. ರಾಗಿ ಮುದ್ದೆ or रागी मुड्डे)
 * Secondary: English canonical food name (only when selected language is NOT English)
 */
export const DualFoodName: React.FC<{
  foodName: string;
  className?: string;
  miniClassName?: string;
  inline?: boolean;
}> = ({
  foodName,
  className = 'font-bold text-[#223030]',
  miniClassName = 'text-xs text-[#523D35]/80 font-medium mt-0.5',
  inline = false
}) => {
  const { tFood, isEnglish } = useLanguage();

  if (isEnglish) {
    return <span className={className}>{foodName}</span>;
  }

  const { primary, secondary } = tFood(foodName);

  if (inline) {
    return (
      <span className="inline-flex items-baseline gap-1.5 flex-wrap">
        <span className={className}>{primary}</span>
        {secondary && (
          <span className={miniClassName}>({secondary})</span>
        )}
      </span>
    );
  }

  return (
    <div className="flex flex-col text-left">
      <span className={className}>{primary}</span>
      {secondary && (
        <span className={miniClassName}>{secondary}</span>
      )}
    </div>
  );
};

